#!/usr/bin/env python3
"""Stretch the frozen original Cloud obstacles vertically, anchored to the floor.

Run with isaacsim/python.sh. Always rebuild from the compressed 20m source,
so rerunning this script cannot accidentally double the height again.
"""
import hashlib
import json
from pathlib import Path
import tarfile
import tempfile
import numpy as np
from pxr import Gf, Usd, UsdGeom
from robot_visual import attach as attach_robot_visual

ROOT = Path(__file__).resolve().parents[2]
FOLDER = ROOT/'scenes/ego_swarm_cloud'
SOURCE_SCENE_SHA = 'cfcc22694241eb2ca5e506060c136a2f9fe5b3b5e2efd76cf0d44a1da26ed1ca'
SOURCE_GRID_SHA = 'e4e7e4301ae0ba6ae129bf813285ceda6d5f625f80a00b65284368682d9e68b8'


def sha(data):
    return hashlib.sha256(data).hexdigest()


def build():
    with tarfile.open(FOLDER/'height20_source.tar.gz') as archive:
        scene_bytes=archive.extractfile('ego_swarm_cloud_navigation.usd').read()
        grid_bytes=archive.extractfile('occupancy.bin').read()
        old=json.load(archive.extractfile('manifest.json'))
        routes=json.load(archive.extractfile('routes.json'))
        route300=json.load(archive.extractfile('route300.json'))
    assert sha(scene_bytes)==SOURCE_SCENE_SHA and sha(grid_bytes)==SOURCE_GRID_SHA
    assert old['shape']==[1200,300,50] and old['resolution']==.4
    # Original voxel surfaces span z=-.2..19.8. Anchoring at -.2 keeps the
    # ground unchanged. z_new=2*z_old+.2 maps each old cell to two .4m cells.
    with tempfile.TemporaryDirectory(prefix='ego_cloud_height_') as temporary:
        source=Path(temporary)/'source.usd';source.write_bytes(scene_bytes)
        stage=Usd.Stage.Open(str(source))
        for path in old['appearance']['targets']:
            prim=stage.GetPrimAtPath(path)
            api=UsdGeom.XformCommonAPI(prim)
            api.SetScale(Gf.Vec3f(4,4,8))
            api.SetTranslate(Gf.Vec3d(0,0,.2))
            # Indexed vertex colors move with their original surface vertices.
            # Do not re-bin the old 20m palette, tile it, or stretch the robot.
        metadata=json.loads(stage.GetRootLayer().customLayerData['fovNavigationJson'])
        metadata.update(mapIdentity='ego2p6_unified_height40_v2',
                        occupancyShape=[1200,300,100],verticalScale=2.,heightStretchAnchorZ=-.2)
        stage.GetRootLayer().customLayerData={'fovNavigationJson':json.dumps(metadata)}
        robot_visual=attach_robot_visual(stage)
        target=FOLDER/'height40_build_tmp.usdc'
        stage.GetRootLayer().Export(str(target))
        target.replace(FOLDER/old['scene'])
    grid=np.frombuffer(grid_bytes,dtype=np.uint8).reshape(old['shape'])
    grown=np.repeat(grid,2,axis=2)
    target=FOLDER/'height40_grid_tmp.bin';grown.tofile(target);target.replace(FOLDER/'occupancy.bin')
    manifest=dict(old)
    manifest.update(robot_visual=robot_visual,map_identity=metadata['mapIdentity'],shape=[1200,300,100],
        extent=[480,120,40],spawn=old['start'],
        scene_sha256=sha((FOLDER/old['scene']).read_bytes()),
        occupancy_sha256=sha((FOLDER/'occupancy.bin').read_bytes()),
        height_stretch=dict(scale=2.,anchor_z_m=-.2,formula='z_new = 2*z_old + 0.2',
            source_bundle='height20_source.tar.gz',source_scene_sha256=SOURCE_SCENE_SHA,
            source_occupancy_sha256=SOURCE_GRID_SHA,ground_robot_and_sensors_unchanged=False,ground_and_sensor_rig_unchanged=True,robot_visual_replaced=True),
        working_bounds=dict(enabled=True,min_x=-80.,max_x=399.8,min_y=-60.,max_y=59.8,min_z=0.,max_z=39.8),
        overview_eye=[150,-340,210],overview_target=[150,0,15],
        first_person_eye=[-64,-40,12],first_person_target=[-30,-5,15])
    manifest['appearance']=dict(old['appearance'],
        height_range_m=[-.2,39.8],vertical_scale=2.,
        note='Original indexed vertex colors preserved exactly; gradient stretched with geometry from 20m to 40m.')
    target=FOLDER/'manifest.tmp.json';target.write_text(json.dumps(manifest,indent=2)+'\n');target.replace(FOLDER/'manifest.json')
    header='// Generated by scripts/scene_tools/build_cloud_height_map.py. Exact 40m Cloud bytes.\n'
    header+='static const char* kHeight40CloudScene = "'+manifest['scene_sha256']+'";\n'
    header+='static const char* kHeight40CloudOccupancy = "'+manifest['occupancy_sha256']+'";\n'
    (ROOT/'src/pc_gvf/config/generated_scene_identity/cloud_height_registry.inc').write_text(header)
    for route in routes['routes']+[route300]:
        for key in ['start','goal','requested_start','requested_goal']:
            if key in route:route[key][2]=2*float(route[key][2])+.2
        # Old seed checks belong to the source map, not to this rebuilt file.
        route.pop('seed_start_passed',None);route.pop('seed_goal_passed',None)
    routes.update(version='ego2p6_height40_multiroute_v2',nominal_height_range_m=[0,40],
                  endpoint_z_m=20.2,scene_sha256=manifest['scene_sha256'],
                  occupancy_sha256=manifest['occupancy_sha256'],
                  height_transform='z_new=2*z_old+.2; horizontal endpoints unchanged',
                  validation_note='Current endpoint certification is recorded separately; no previous flight result is transferred.')
    route300.update(height_m=20.2,nominal_map_height_m=[0,40],
                    height_transform='z_new=2*z_old+.2; horizontal endpoints unchanged',
                    scene_sha256=manifest['scene_sha256'],occupancy_sha256=manifest['occupancy_sha256'])
    for name,value in [('routes.json',routes),('route300.json',route300)]:
        destination=ROOT/'src/pc_gvf/config'/name;temporary=destination.with_suffix('.tmp.json')
        temporary.write_text(json.dumps(value,indent=2)+'\n');temporary.replace(destination)
    print(json.dumps({k:manifest[k] for k in ['map_identity','shape','extent','scene_sha256','occupancy_sha256']},indent=2))


if __name__=='__main__':build()
