#!/usr/bin/env python3
"""Authoritative step-1 configuration; sync the two C++ header copies explicitly."""
import argparse
import hashlib
import json
from pathlib import Path
import shlex

ROOT = Path(__file__).resolve().parents[1]
CONFIG_PATH = ROOT / 'src/new_controller/config/base_step1.json'


def load_config():
    raw = CONFIG_PATH.read_bytes()
    c = json.loads(raw)
    expected = dict(max_speed_mps=12., velocity_limit_mode='norm_3d',
                    vertical_speed_limit_mps=None, local_range_m=4., control_period_s=.005,
                    physics_dt_s=.005, camera_hz=200, time_scale=.02, plant_tau_s=.10,
                    body_radius_m=.10, plant_acceleration_mps2=150.,
                    reference_command_acceleration_mps2=20., motion_output_enabled=False)
    if any(c.get(k) != v for k, v in expected.items()):
        raise ValueError('step-1 profile differs from its reviewed parameter contract')
    return c, hashlib.sha256(raw).hexdigest()


def header(c, sha):
    constants = '\n'.join(f'  static constexpr double {k}={c[k]!r};' for k in (
        'max_speed_mps', 'local_range_m', 'control_period_s', 'physics_dt_s', 'time_scale',
        'plant_tau_s', 'body_radius_m', 'plant_acceleration_mps2',
        'reference_command_acceleration_mps2'))
    return ('// Generated by scripts/base_config.py --sync; edit config/base_step1.json.\n'
            '#pragma once\n#include <cstdint>\nnamespace ego4p0 {\nstruct BaseConfig {\n' + constants +
            f'\n  static constexpr int camera_hz={c["camera_hz"]};\n'
            '  static constexpr int64_t period_ns=5000000;\n'
            '  static constexpr bool motion_output_enabled=false;\n'
            f'  static constexpr const char *sha256="{sha}";\n'
            f'  static constexpr const char *json=R"config({json.dumps(c, separators=(",", ":"))})config";\n'
            '};\n} // namespace ego4p0\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--sync', action='store_true')
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--shell', action='store_true')
    args = parser.parse_args()
    c, sha = load_config()
    generated = header(c, sha)
    for package in ('src/new_controller', 'src/new_controller/ldlt'):
        path = ROOT / package / 'include/new_controller/base_config.hpp'
        if args.sync:
            path.write_text(generated)
        elif args.check and (not path.exists() or path.read_text() != generated):
            raise SystemExit('C++ configuration is stale: ' + str(path))
    if args.shell:
        values = dict(JOYSTICK_HORIZONTAL_SPEED=c['max_speed_mps'],
                      JOYSTICK_VERTICAL_SPEED=c['max_speed_mps'], JOYSTICK_VELOCITY_LIMIT_MODE='norm_3d',
                      ISAAC_PLANT_ACCEL=c['plant_acceleration_mps2'], ISAAC_PLANT_TAU=c['plant_tau_s'],
                      EGO4P2_BASE_CONFIG_SHA256=sha)
        for k, v in values.items():
            print(f'export {k}={shlex.quote(str(v))}')
    else:
        print(json.dumps(dict(config=c, config_sha256=sha, cpp_headers_checked=args.check), indent=2))


if __name__ == '__main__':
    main()
